#!/usr/bin/env node
/**
 * Generates the static import tables for Excel content, so adding a mission or exercise never means
 * hand-editing six files. Cloudflare Workers have no filesystem, so content is bundled with static JSON
 * imports; this script writes them from the folders:
 *   content/excel/exercises/<id>.json            learner-safe exercise      -> components/excel/registry.generated.ts
 *   content/excel/missions/<slug>.json           learner-safe mission       -> components/excel/registry.generated.ts
 *   content/excel/exercises/<id>.key.json        SERVER-ONLY exercise key   -> server/excel-registry.generated.ts
 *   content/excel/missions/<slug>.keys.json      SERVER-ONLY assessment key -> server/excel-registry.generated.ts
 * Run: node scripts/gen-excel-registry.mjs        (registry.test.ts fails if the generated files are stale)
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const appDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const contentDir = path.resolve(appDir, "..", "..", "content", "excel");

const list = (dir) => (fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => f.endsWith(".json")).sort() : []);
const isKey = (f) => f.endsWith(".key.json") || f.endsWith(".keys.json");

function table(name, type, entries, relBase) {
  const imports = entries.map(([, file], i) => `import ${name}_${i} from "${relBase}/${file}";`);
  const rows = entries.map(([id], i) => `  ${JSON.stringify(id)}: ${name}_${i} as unknown as ${type},`);
  return { imports, rows };
}

export function generate() {
  const exDir = path.join(contentDir, "exercises");
  const miDir = path.join(contentDir, "missions");
  const exercises = list(exDir).filter((f) => !isKey(f)).map((f) => [f.replace(/\.json$/, ""), `exercises/${f}`]);
  const exerciseKeys = list(exDir).filter((f) => f.endsWith(".key.json")).map((f) => [f.replace(/\.key\.json$/, ""), `exercises/${f}`]);
  const missions = list(miDir).filter((f) => !isKey(f)).map((f) => [f.replace(/\.json$/, ""), `missions/${f}`]);
  const missionKeys = list(miDir).filter((f) => f.endsWith(".keys.json")).map((f) => [f.replace(/\.keys\.json$/, ""), `missions/${f}`]);

  const banner = "// GENERATED by scripts/gen-excel-registry.mjs. Do not edit by hand: run `pnpm --filter @flightdeck/web registry:excel`.\n";

  const ex = table("ex", "ExerciseDefinition", exercises, "../../../../content/excel");
  const mi = table("mi", "ExcelMission", missions, "../../../../content/excel");
  const learner =
    banner +
    "// LEARNER-SAFE content only. Never import a *.key.json or *.keys.json here.\n" +
    'import type { ExerciseDefinition } from "@flightdeck/excel-engine";\n' +
    'import type { ExcelMission } from "./missions";\n' +
    [...ex.imports, ...mi.imports].join("\n") +
    "\n\nexport const EXERCISE_DEFINITIONS: Record<string, ExerciseDefinition> = {\n" + ex.rows.join("\n") + "\n};\n\n" +
    "export const MISSION_DEFINITIONS: Record<string, ExcelMission> = {\n" + mi.rows.join("\n") + "\n};\n";

  const ek = table("ek", "ExerciseKey", exerciseKeys, "../../../content/excel");
  const mk = table("mk", "ExcelMissionKeys", missionKeys, "../../../content/excel");
  const server =
    banner +
    "// SERVER-ONLY (answer keys). Import only from apps/web/server/**; scripts/check-key-leak.mjs guards the browser bundle.\n" +
    'import type { ExerciseKey } from "@flightdeck/excel-engine";\n' +
    'import type { ExcelMissionKeys } from "../components/excel/missions";\n' +
    [...ek.imports, ...mk.imports].join("\n") +
    "\n\nexport const EXERCISE_KEYS: Record<string, ExerciseKey> = {\n" + ek.rows.join("\n") + "\n};\n\n" +
    "export const MISSION_KEYS: Record<string, ExcelMissionKeys> = {\n" + mk.rows.join("\n") + "\n};\n";

  return {
    learner,
    server,
    learnerPath: path.join(appDir, "components", "excel", "registry.generated.ts"),
    serverPath: path.join(appDir, "server", "excel-registry.generated.ts"),
  };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const g = generate();
  fs.writeFileSync(g.learnerPath, g.learner);
  fs.writeFileSync(g.serverPath, g.server);
  console.log(`registry written: ${g.learnerPath} and ${g.serverPath}`);
}
