// Generates the physical ERD, data dictionary and RLS/grant matrix from the migrated schema,
// so G1 documents cannot drift from the code. Run: pnpm --filter @flightdeck/database docs
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createDb } from '../test/harness.ts';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const db = await createDb('');
const q = async <T = Record<string, unknown>>(sql: string) => (await db.pg.query(sql)).rows as T[];

const SCHEMAS = `('public', 'app_private')`;
const classify = (schema: string, table: string) => {
  if (schema === 'app_private') return 'Restricted (server-only)';
  if (['tracks', 'courses', 'course_versions', 'missions', 'mission_steps', 'exercises'].includes(table))
    return 'Public when published';
  if (['assessments', 'assessment_items'].includes(table)) return 'Authenticated when published';
  return 'Personal (owner-only)';
};

type Col = { schema: string; table: string; column: string; type: string; nullable: string; def: string | null; pos: number };
const cols = await q<Col>(`
  select c.table_schema as schema, c.table_name as "table", c.column_name as column,
         case when c.data_type = 'USER-DEFINED' then c.udt_name
              when c.data_type = 'ARRAY' then c.udt_name
              when c.character_maximum_length is not null then c.data_type || '(' || c.character_maximum_length || ')'
              when c.data_type = 'numeric' and c.numeric_precision is not null then 'numeric(' || c.numeric_precision || ',' || c.numeric_scale || ')'
              else c.data_type end as type,
         c.is_nullable as nullable, c.column_default as def, c.ordinal_position as pos
    from information_schema.columns c
   where c.table_schema in ${SCHEMAS}
   order by c.table_schema, c.table_name, c.ordinal_position`);

type Key = { schema: string; table: string; column: string; kind: string; ref: string | null };
const keys = await q<Key>(`
  select n.nspname as schema, t.relname as "table", a.attname as column,
         case con.contype when 'p' then 'PK' when 'f' then 'FK' when 'u' then 'UQ' end as kind,
         case when con.contype = 'f' then rn.nspname || '.' || rt.relname end as ref
    from pg_constraint con
    join pg_class t on t.oid = con.conrelid
    join pg_namespace n on n.oid = t.relnamespace
    join lateral unnest(con.conkey) k(attnum) on true
    join pg_attribute a on a.attrelid = t.oid and a.attnum = k.attnum
    left join pg_class rt on rt.oid = con.confrelid
    left join pg_namespace rn on rn.oid = rt.relnamespace
   where n.nspname in ${SCHEMAS} and con.contype in ('p', 'f', 'u')`);
const keyTags = (s: string, t: string, c: string) =>
  [...new Set(keys.filter((k) => k.schema === s && k.table === t && k.column === c)
    .map((k) => (k.kind === 'FK' ? `FK→${k.ref}` : k.kind)))].join(' ');

const tables = [...new Map(cols.map((c) => [`${c.schema}.${c.table}`, c])).values()];

// ---------- ERD (Mermaid) ----------
type Rel = { child: string; parent: string; column: string; unique: boolean };
const rels = await q<Rel>(`
  select n.nspname || '_' || t.relname as child, rn.nspname || '_' || rt.relname as parent,
         string_agg(a.attname, ',') as column,
         exists (select 1 from pg_constraint u where u.conrelid = con.conrelid and u.contype in ('u','p')
                  and u.conkey = con.conkey) as unique
    from pg_constraint con
    join pg_class t on t.oid = con.conrelid join pg_namespace n on n.oid = t.relnamespace
    join pg_class rt on rt.oid = con.confrelid join pg_namespace rn on rn.oid = rt.relnamespace
    join lateral unnest(con.conkey) k(attnum) on true
    join pg_attribute a on a.attrelid = t.oid and a.attnum = k.attnum
   where con.contype = 'f' and n.nspname in ${SCHEMAS}
   group by 1, 2, con.conrelid, con.conkey order by 1, 2`);
const ent = (s: string) => s.replace(/^public_/, '').replace(/^app_private_/, 'private_').replace(/^auth_/, 'auth_');
const erdLines = ['erDiagram'];
for (const r of rels) erdLines.push(`  ${ent(r.parent)} ||--${r.unique ? 'o|' : 'o{'} ${ent(r.child)} : "${r.column}"`);
for (const t of tables) {
  erdLines.push(`  ${ent(`${t.schema}_${t.table}`)} {`);
  for (const c of cols.filter((x) => x.schema === t.schema && x.table === t.table)) {
    const tag = keyTags(c.schema, c.table, c.column).split(' ').filter((x) => x === 'PK' || x.startsWith('FK')).map((x) => (x.startsWith('FK') ? 'FK' : x));
    erdLines.push(`    ${c.type.replace(/[^a-zA-Z0-9_]/g, '_')} ${c.column}${tag.length ? ' ' + [...new Set(tag)].join(',') : ''}`);
  }
  erdLines.push('  }');
}

const header = (title: string) =>
  `# ${title}\n\n> Generated by \`packages/database/scripts/generate-docs.ts\` from the migrated schema (PostgreSQL 17 / PGlite). Do not edit by hand.\n> Status: AI-drafted, pending Data Architect + Security Architect review.\n\n`;

mkdirSync(join(root, 'docs', 'data'), { recursive: true });
writeFileSync(join(root, 'docs', 'data', 'ERD.md'), header('FlightDeck physical ERD (FD-D01)') +
  `Schemas: \`public\` (exposed via Supabase Data API, every table behind RLS), \`app_private\` (not exposed; server-only), \`auth\` (Supabase-managed).\n` +
  `Entity names: \`private_*\` = \`app_private\` schema.\n\n\`\`\`mermaid\n${erdLines.join('\n')}\n\`\`\`\n`);

// ---------- Data dictionary ----------
let dict = header('FlightDeck data dictionary (FD-D01)');
dict += '| Table | Sensitivity | Columns |\n|---|---|---|\n';
for (const t of tables) dict += `| \`${t.schema}.${t.table}\` | ${classify(t.schema, t.table)} | ${cols.filter((c) => c.schema === t.schema && c.table === t.table).length} |\n`;
for (const t of tables) {
  dict += `\n## ${t.schema}.${t.table}\nSensitivity: **${classify(t.schema, t.table)}**\n\n| Column | Type | Null | Default | Keys |\n|---|---|---|---|---|\n`;
  for (const c of cols.filter((x) => x.schema === t.schema && x.table === t.table)) {
    dict += `| ${c.column} | ${c.type} | ${c.nullable === 'YES' ? 'yes' : 'no'} | ${c.def ? '`' + c.def.replace(/\|/g, '\\|') + '`' : ''} | ${keyTags(c.schema, c.table, c.column)} |\n`;
  }
}
writeFileSync(join(root, 'docs', 'data', 'DATA-DICTIONARY.md'), dict);

// ---------- Grant + RLS matrix ----------
type Priv = { schema: string; table: string; grantee: string; privs: string };
const tablePrivs = await q<Priv>(`
  select table_schema as schema, table_name as "table", grantee, string_agg(privilege_type, ',' order by privilege_type) as privs
    from information_schema.role_table_grants
   where table_schema in ${SCHEMAS} and grantee in ('anon', 'authenticated', 'service_role')
   group by 1, 2, 3`);
type ColPriv = { schema: string; table: string; grantee: string; privilege: string; columns: string };
const colPrivs = await q<ColPriv>(`
  select cp.table_schema as schema, cp.table_name as "table", cp.grantee, cp.privilege_type as privilege,
         string_agg(cp.column_name, ', ' order by cp.column_name) as columns
    from information_schema.column_privileges cp
   where cp.table_schema in ${SCHEMAS} and cp.grantee in ('anon', 'authenticated')
     and cp.privilege_type in ('INSERT', 'UPDATE')
     and not exists (select 1 from information_schema.role_table_grants tg
                      where tg.table_schema = cp.table_schema and tg.table_name = cp.table_name
                        and tg.grantee = cp.grantee and tg.privilege_type = cp.privilege_type)
   group by 1, 2, 3, 4`);
type Pol = { schema: string; table: string; name: string; cmd: string; roles: string; qual: string | null; check: string | null };
const pols = await q<Pol>(`
  select schemaname as schema, tablename as "table", policyname as name, cmd, array_to_string(roles, ',') as roles,
         qual, with_check as check
    from pg_policies where schemaname in ${SCHEMAS} and not ('app_definer' = any(roles)) order by 1, 2, 3`);

const cell = (s: string, t: string, who: string) => {
  const full = tablePrivs.find((p) => p.schema === s && p.table === t && p.grantee === who)?.privs.split(',') ?? [];
  const partial = colPrivs.filter((p) => p.schema === s && p.table === t && p.grantee === who)
    .map((p) => `${p.privilege}(${p.columns})`);
  return [...full, ...partial].join(' ') || '—';
};
let matrix = header('FlightDeck grants + RLS matrix (FD-S01 / FD-D01)');
matrix += 'Evidence: `pnpm test:rls` (RLS-T01..T24). `—` = no privilege (default deny). service_role bypasses RLS and is server-only.\n\n';
matrix += '| Table | Sensitivity | anon | authenticated | service_role |\n|---|---|---|---|---|\n';
const csv = ['schema,table,sensitivity,anon,authenticated,service_role'];
for (const t of tables) {
  const row = [cell(t.schema, t.table, 'anon'), cell(t.schema, t.table, 'authenticated'), cell(t.schema, t.table, 'service_role')];
  matrix += `| \`${t.schema}.${t.table}\` | ${classify(t.schema, t.table)} | ${row.join(' | ')} |\n`;
  csv.push([t.schema, t.table, classify(t.schema, t.table), ...row].map((v) => `"${v}"`).join(','));
}
matrix += '\n## Policies\n\n| Table | Policy | Command | Roles | USING | WITH CHECK |\n|---|---|---|---|---|---|\n';
const clean = (s: string | null) => (s ? '`' + s.replace(/\s+/g, ' ').replace(/\|/g, '\\|') + '`' : '');
for (const p of pols) matrix += `| ${p.schema}.${p.table} | ${p.name} | ${p.cmd} | ${p.roles} | ${clean(p.qual)} | ${clean(p.check)} |\n`;
mkdirSync(join(root, 'docs', 'security'), { recursive: true });
writeFileSync(join(root, 'docs', 'security', 'RLS-MATRIX.md'), matrix);
writeFileSync(join(root, 'docs', 'security', 'RLS-MATRIX.csv'), csv.join('\n') + '\n');

console.log(`tables=${tables.length} columns=${cols.length} fks=${rels.length} policies=${pols.length}`);
await db.pg.close();
